"""Generate JSON Schema and strict TypeScript from canonical Pydantic models."""

import json
from pathlib import Path

from rewind.models import AnalyzeRequest, Case, Job

ROOT = Path(__file__).resolve().parents[2]


def ts(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "object" and isinstance(schema.get("additionalProperties"), dict):
        return f"Record<string, {ts(schema['additionalProperties'])}>"
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate():
    definitions = {}
    for model in (Case, Job, AnalyzeRequest):
        schema = model.model_json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    output = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$defs": definitions,
    }
    (ROOT / "shared/schema.json").write_text(json.dumps(output, indent=2) + "\n")
    lines = ["// Generated by backend/scripts/generate_types.py. Do not edit.", ""]
    for name, schema in definitions.items():
        if schema.get("type") != "object":
            lines += [f"export type {name} = {ts(schema)}", ""]
            continue
        lines.append(f"export interface {name} {{")
        for prop, value in schema.get("properties", {}).items():
            lines.append(f"  {prop}: {ts(value)}")
        lines += ["}", ""]
    target = ROOT / "frontend/app/types/generated.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines))


if __name__ == "__main__":
    generate()
